// Флаг автообновления таблицы. Если false, события NOTIFY игнорируются клиентом.
let signalRТаблицыВключен = false;

// Защита от параллельных обновлений: пока один fetch выполняется, второй не запускаем.
let идетОбновлениеТаблицы = false;

// ------------------------------------------------------------
// События учебного Hub.
// ------------------------------------------------------------
подключение.on("ПринятьСистемноеСообщение", (сообщение, время) => {
    подсветитьШаг("hub");
    добавитьЗаписьВЖурнал(время, "SignalR Hub", сообщение);
});

подключение.on("ПолучитьСообщениеОтСервера", (имя, текст, idПодключения, время) => {
    подсветитьШаг("clients");
    добавитьЗаписьВЖурнал(
        время,
        "Clients.All",
        `${имя}: ${текст} | отправитель ConnectionId: ${idПодключения}`);
});

подключение.on("ПолучитьВремяСервера", (сообщение) => {
    подсветитьШаг("clients");
    добавитьЗаписьВЖурнал(получитьВремя(), "Clients.Caller", сообщение);
});

подключение.on("ПолучитьКомандуОтКлиента", (idПодключения, команда, время) => {
    подсветитьШаг("clients");
    добавитьЗаписьВЖурнал(
        время,
        "Команда всем клиентам",
        `Клиент ${idПодключения} отправил команду: ${команда}`);
});

подключение.on("ПолучитьСобытиеФоновогоСервиса", (номер, текст, время) => {
    подсветитьШаг("service");
    добавитьЗаписьВЖурнал(
        время,
        "BackgroundService + IHubContext",
        `${текст}. Это событие пришло не от кнопки клиента, а от сервера.`);
});

подключение.on("ПодсветитьЭлементСхемы", (названиеШага) => {
    подсветитьШаг(названиеШага);
});

// ------------------------------------------------------------
// События Hub таблицы.
// ------------------------------------------------------------
подключениеКСтранице.on("ИзмененияДанных", async function (сообщение) {
    // Если пользователь выключил SignalR таблицы, уведомления БД игнорируем.
    if (!signalRТаблицыВключен) {
        return;
    }

    const таблицы = сообщение?.tables ?? сообщение?.Таблицы ?? [];
    const канал = сообщение?.channel ?? сообщение?.канал ?? каналСтраницы;

    добавитьЗаписьВЖурнал(
        получитьВремя(),
        "PostgreSQL LISTEN/NOTIFY",
        `Получено уведомление из канала ${канал}. Таблицы: ${таблицы.join(", ") || "не указаны"}`);

    await обновитьДанныеТаблицы("уведомление из БД", таблицы);
});

подключениеКСтранице.onreconnecting(() => {
    установитьСтатусSignalRТаблицы("переподключение...", "желтый");
    добавитьЗаписьВЖурнал(получитьВремя(), "SignalR таблицы", "Соединение потеряно, идет переподключение.");
});

подключениеКСтранице.onreconnected(async () => {
    if (signalRТаблицыВключен) {
        await подключениеКСтранице.invoke("ПодключениеКСтранице", каналСтраницы);
        установитьСтатусSignalRТаблицы("включен", "зеленый");
        добавитьЗаписьВЖурнал(получитьВремя(), "SignalR таблицы", "Переподключение выполнено, группа канала восстановлена.");
    }
});

подключениеКСтранице.onclose(() => {
    if (signalRТаблицыВключен) {
        установитьСтатусSignalRТаблицы("отключен", "красный");
        добавитьЗаписьВЖурнал(получитьВремя(), "SignalR таблицы", "Соединение закрыто.");
    }
});

