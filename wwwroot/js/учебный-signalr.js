// ============================================================================
// учебный-signalr.js
// Клиентская логика страницы.
//
// В этом файле намеренно много комментариев, потому что проект используется как
// шпаргалка по ASP.NET Core MVC + SignalR + PostgreSQL LISTEN/NOTIFY.
//
// На странице есть два независимых SignalR-соединения:
// 1) подключение — учебный Hub для демонстрации сообщений клиент ↔ сервер.
// 2) подключениеКСтранице — Hub таблицы. Через него включается/выключается
//    автообновление таблицы по уведомлениям из PostgreSQL и выполняется ручное
//    разовое обновление.
// ============================================================================

// Учебное соединение. Работает только после нажатия кнопки «Подключиться к учебному Hub».
const подключение = new signalR.HubConnectionBuilder()
    .withUrl("/УчебныйSignalRHub")
    .withAutomaticReconnect()
    .configureLogging(signalR.LogLevel.Information)
    .build();

// Соединение для таблицы. Оно может временно включаться даже при ручном обновлении.
const подключениеКСтранице = new signalR.HubConnectionBuilder()
    .withUrl("/ТаблицаSignalRHub")
    .withAutomaticReconnect()
    .configureLogging(signalR.LogLevel.Information)
    .build();

// ------------------------------------------------------------
// HTML-элементы.
// ------------------------------------------------------------
const кнопкаПодключиться = document.getElementById("кнопкаПодключиться");
const кнопкаОтключиться = document.getElementById("кнопкаОтключиться");
const кнопкаЗапроситьВремя = document.getElementById("кнопкаЗапроситьВремя");
const кнопкаОтправитьСообщение = document.getElementById("кнопкаОтправитьСообщение");
const кнопкаОтправитьКоманду = document.getElementById("кнопкаОтправитьКоманду");
const кнопкаОчиститьЖурнал = document.getElementById("кнопкаОчиститьЖурнал");

const имяПользователя = document.getElementById("имяПользователя");
const текстСообщения = document.getElementById("текстСообщения");
const текстКоманды = document.getElementById("текстКоманды");

const текстСтатуса = document.getElementById("текстСтатуса");
const лампочкаСтатуса = document.getElementById("лампочкаСтатуса");
const журналСобытий = document.getElementById("журналСобытий");

const кнопкаПоказатьДанныеИзБазы = document.getElementById("кнопкаПоказатьДанныеИзБазы");
const кнопкаСкрытьДанныеИзБазы = document.getElementById("кнопкаСкрытьДанныеИзБазы");
const блокТаблицыБазыДанных = document.getElementById("блокТаблицыБазыДанных");

const кнопкаSignalRТаблицы = document.getElementById("кнопкаSignalRТаблицы");
const кнопкаОбновитьТаблицу = document.getElementById("кнопкаОбновитьТаблицу");
