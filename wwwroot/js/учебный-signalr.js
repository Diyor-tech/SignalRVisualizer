// Включает автообновление таблицы:
// - запускает SignalR-соединение;
// - вызывает Hub-метод ПодключениеКСтранице;
// - добавляет текущий браузер в группу канала БД.
async function включитьSignalRТаблицы() {
    try {
        if (!каналСтраницы) {
            throw new Error("каналСтраницы не задан");
        }

        установитьКнопкиТаблицы(false);

        if (подключениеКСтранице.state === signalR.HubConnectionState.Disconnected) {
            await подключениеКСтранице.start();
        }

        await подключениеКСтранице.invoke("ПодключениеКСтранице", каналСтраницы);

        signalRТаблицыВключен = true;
        кнопкаSignalRТаблицы.textContent = "Выключить SignalR таблицы";
        установитьСтатусSignalRТаблицы("включен", "зеленый");
        подсветитьШаг("service");
        добавитьЗаписьВЖурнал(получитьВремя(), "SignalR таблицы", `Подключились к группе канала ${каналСтраницы}.`);
    }
    catch (ошибка) {
        signalRТаблицыВключен = false;
        установитьСтатусSignalRТаблицы("ошибка включения", "красный");
        добавитьЗаписьВЖурнал(получитьВремя(), "Ошибка SignalR таблицы", ошибка.toString());
    }
    finally {
        установитьКнопкиТаблицы(true);
    }
}

// Выключает автообновление таблицы:
// - удаляет подключение из группы канала;
// - закрывает SignalR-соединение таблицы;
// - новые уведомления БД больше не перерисовывают таблицу в этом браузере.
async function выключитьSignalRТаблицы() {
    try {
        установитьКнопкиТаблицы(false);

        if (подключениеКСтранице.state === signalR.HubConnectionState.Connected) {
            await подключениеКСтранице.invoke("ОтключениеОтСтраницы", каналСтраницы);
            await подключениеКСтранице.stop();
        }

        signalRТаблицыВключен = false;
        кнопкаSignalRТаблицы.textContent = "Включить SignalR таблицы";
        установитьСтатусSignalRТаблицы("выключен", "красный");
        добавитьЗаписьВЖурнал(получитьВремя(), "SignalR таблицы", "Автообновление таблицы по уведомлениям БД выключено.");
    }
    catch (ошибка) {
        добавитьЗаписьВЖурнал(получитьВремя(), "Ошибка SignalR таблицы", ошибка.toString());
    }
    finally {
        установитьКнопкиТаблицы(true);
    }
}

// Ручное обновление таблицы через SignalR.
// Важно: эта кнопка работает даже когда автообновление выключено.
// Для этого соединение временно открывается, вызывает Hub и после обновления
// снова закрывается, если до нажатия кнопки автообновление было выключено.
async function обновитьТаблицуЧерезSignalRОдинРаз() {
    const былВключенДоОбновления = signalRТаблицыВключен;

    try {
        установитьКнопкиТаблицы(false);

        if (!каналСтраницы) {
            throw new Error("каналСтраницы не задан");
        }

        // Даже если автообновление выключено, для разового запроса временно поднимаем SignalR-соединение.
        if (подключениеКСтранице.state === signalR.HubConnectionState.Disconnected) {
            await подключениеКСтранице.start();
        }

        подсветитьШаг("hub");
        const ответ = await подключениеКСтранице.invoke("ЗапроситьРазовоеОбновлениеТаблицы", каналСтраницы);
        const таблицы = ответ?.tables ?? ответ?.таблицы ?? ответ?.Таблицы ?? ["_Диспозиция_поковок_ТА"];

        добавитьЗаписьВЖурнал(
            получитьВремя(),
            "Кнопка обновления",
            `Hub подтвердил разовое обновление. Таблицы: ${таблицы.join(", ")}`);

        await обновитьДанныеТаблицы("кнопка обновления через SignalR", таблицы);
    }
    catch (ошибка) {
        добавитьЗаписьВЖурнал(получитьВремя(), "Ошибка обновления таблицы", ошибка.toString());
    }
    finally {
        // Если автообновление до ручного запроса было выключено, возвращаем соединение в выключенное состояние.
        if (!былВключенДоОбновления && подключениеКСтранице.state === signalR.HubConnectionState.Connected) {
            await подключениеКСтранице.stop();
            signalRТаблицыВключен = false;
            установитьСтатусSignalRТаблицы("выключен", "красный");
        }

        установитьКнопкиТаблицы(true);
    }
}

// Фактическая перерисовка таблицы.
// SignalR в этом проекте не передает всю таблицу. Он только сообщает причину.
// А HTML строк таблицы получаем обычным MVC-запросом к /Главная/ЧастичнаяОтрисовка.
async function обновитьДанныеТаблицы(причина, таблицы) {
    if (идетОбновлениеТаблицы) {
        добавитьЗаписьВЖурнал(получитьВремя(), "Таблица", "Обновление уже выполняется, повторный запрос пропущен.");
        return;
    }

    идетОбновлениеТаблицы = true;
    установитьКнопкиТаблицы(false);

    try {
        подсветитьШаг("client");

        const response = await fetch(`/Главная/ЧастичнаяОтрисовка?_=${Date.now()}`, {
            method: "GET",
            headers: {
                "X-Requested-With": "XMLHttpRequest"
            },
            cache: "no-store"
        });

        if (!response.ok) {
            throw new Error(`HTTP ${response.status}: ${response.statusText}`);
        }

        const html = await response.text();
        const container = document.getElementById("Таблица");
        container.innerHTML = html;

        обновитьСтатусТаблицыПослеПерерисовки();
        подсветитьШаг("clients");

        добавитьЗаписьВЖурнал(
            получитьВремя(),
            "MVC PartialView",
            `Таблица обновлена. Причина: ${причина}. ${таблицы && таблицы.length ? "Таблицы: " + таблицы.join(", ") : ""}`);
    }
    catch (ошибка) {
        добавитьЗаписьВЖурнал(получитьВремя(), "Ошибка обновления таблицы", ошибка.toString());
    }
    finally {
        идетОбновлениеТаблицы = false;
        установитьКнопкиТаблицы(true);
    }
}

