function включитьКнопкиУчебногоHub(подключено) {
    if (кнопкаПодключиться) кнопкаПодключиться.disabled = подключено;
    if (кнопкаОтключиться) кнопкаОтключиться.disabled = !подключено;
    if (кнопкаЗапроситьВремя) кнопкаЗапроситьВремя.disabled = !подключено;
    if (кнопкаОтправитьСообщение) кнопкаОтправитьСообщение.disabled = !подключено;
    if (кнопкаОтправитьКоманду) кнопкаОтправитьКоманду.disabled = !подключено;
}

function установитьКнопкиТаблицы(доступны) {
    if (кнопкаSignalRТаблицы) кнопкаSignalRТаблицы.disabled = !доступны;
    if (кнопкаОбновитьТаблицу) кнопкаОбновитьТаблицу.disabled = !доступны;
}

function установитьСтатус(текст, цвет) {
    if (!текстСтатуса || !лампочкаСтатуса) return;

    текстСтатуса.textContent = текст;
    лампочкаСтатуса.classList.remove("лампочка-красная", "лампочка-зеленая", "лампочка-желтая");
    лампочкаСтатуса.classList.add(`лампочка-${цвет}`);
}

function установитьСтатусSignalRТаблицы(текст, цвет) {
    if (статусSignalRТаблицы) {
        статусSignalRТаблицы.textContent = текст;
        статусSignalRТаблицы.className = `статус-signalr-таблицы статус-${цвет}`;
    }
}

// После замены tbody пересчитываем количество реальных строк и обновляем время.
function обновитьСтатусТаблицыПослеПерерисовки() {
    const строки = document.querySelectorAll("#Таблица tr.строка-базы-данных:not(.строка-ошибки-бд):not(.строка-пустой-бд)");

    if (количествоСтрокТаблицы) {
        количествоСтрокТаблицы.textContent = String(строки.length);
    }

    if (статусПоследнегоОбновленияТаблицы) {
        статусПоследнегоОбновленияТаблицы.textContent = new Date().toLocaleString("ru-RU");
    }
}

function добавитьЗаписьВЖурнал(время, источник, событие) {
    if (!журналСобытий) return;

    const строка = document.createElement("div");
    строка.className = "строка-журнала";

    строка.innerHTML = `
        <span>${экранироватьHtml(время)}</span>
        <span>${экранироватьHtml(источник)}</span>
        <span>${экранироватьHtml(событие)}</span>
    `;

    журналСобытий.prepend(строка);
}

function подсветитьШаг(названиеШага) {
    const элементы = document.querySelectorAll("[data-step]");

    элементы.forEach(элемент => {
        элемент.classList.remove("активный-узел");
    });

    const нужныйЭлемент = document.querySelector(`[data-step="${названиеШага}"]`);

    if (нужныйЭлемент) {
        нужныйЭлемент.classList.add("активный-узел");

        setTimeout(() => {
            нужныйЭлемент.classList.remove("активный-узел");
        }, 1200);
    }
}

function получитьВремя() {
    return new Date().toLocaleTimeString("ru-RU", {
        hour: "2-digit",
        minute: "2-digit",
        second: "2-digit"
    });
}

// Защита журнала от HTML-вставок. Любой текст из ошибок/сообщений выводим как текст.
function экранироватьHtml(значение) {
    return String(значение)
        .replaceAll("&", "&amp;")
        .replaceAll("<", "&lt;")
        .replaceAll(">", "&gt;")
        .replaceAll('"', "&quot;")
        .replaceAll("'", "&#039;");
}

