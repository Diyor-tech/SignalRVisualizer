// ============================================================================
// Program.cs
// Точка входа ASP.NET Core приложения.
// Здесь создается WebApplicationBuilder, регистрируются MVC, SignalR, фоновые
// службы, маршруты контроллеров и маршруты SignalR Hub.
// ============================================================================

using SignalRVisualizer.Hubs;
using SignalRVisualizer.Services;

// builder — объект настройки приложения ДО запуска.
// Через него добавляем сервисы в DI-контейнер и читаем appsettings.json.
var builder = WebApplication.CreateBuilder(args);

// ---------------------------------------------------------------------------
// 1. Регистрация MVC.
// AddControllersWithViews() включает:
// - контроллеры из папки Controllers;
// - Razor-представления из папки Views;
// - Tag Helpers, нужные для asp-append-version и других MVC-возможностей.
// ---------------------------------------------------------------------------
builder.Services.AddControllersWithViews();

// ---------------------------------------------------------------------------
// 2. Регистрация SignalR.
// SignalR нужен для постоянного соединения браузер ↔ сервер.
// В проекте используются два Hub:
// - УчебныйSignalRHub — демонстрация обычных сообщений клиентам;
// - ТаблицаSignalRHub — управление обновлением таблицы из PostgreSQL.
// ---------------------------------------------------------------------------
builder.Services.AddSignalR();

// ---------------------------------------------------------------------------
// 3. Регистрация фоновых сервисов.
// HostedService запускается вместе с сайтом и работает в фоне.
// ---------------------------------------------------------------------------

// ИмитацияРаботыСервера — учебный сервис. Он раз в несколько секунд отправляет
// событие всем клиентам через IHubContext<УчебныйSignalRHub>.
builder.Services.AddHostedService<ИмитацияРаботыСервера>();

// ПрослушкаКаналовБД — реальный полезный сервис для этого проекта.
// Он подключается к PostgreSQL, выполняет LISTEN и ждет NOTIFY из БД.
// Когда из БД приходит уведомление, сервис отправляет событие в SignalR-группу.
builder.Services.AddHostedService<ПрослушкаКаналовБД>();

// app — уже собранное приложение. Ниже настраивается HTTP-конвейер.
var app = builder.Build();

// В production показываем не технический стек ошибки, а маршрут /Главная/Ошибка.
// В development подробная ошибка полезнее, поэтому middleware не включаем.
if (!app.Environment.IsDevelopment())
{
    app.UseExceptionHandler("/Главная/Ошибка");
}

// Разрешаем отдавать статические файлы из wwwroot:
// css, js, картинки, библиотеку signalr.min.js.
app.UseStaticFiles();

// Включаем маршрутизацию ASP.NET Core.
app.UseRouting();

// Авторизация в учебном проекте не используется, но middleware можно оставить.
// Если позже добавишь Windows Authentication или роли, это место уже будет готово.
app.UseAuthorization();

// ---------------------------------------------------------------------------
// 4. MVC-маршрут.
// Если открыть корень сайта, сработает:
// Controller = ГлавнаяController
// Action     = ПерваяСтраница
// ---------------------------------------------------------------------------
app.MapControllerRoute(
    name: "default",
    pattern: "{controller=Главная}/{action=ПерваяСтраница}/{id?}");

// ---------------------------------------------------------------------------
// 5. SignalR-маршруты.
// Эти адреса должны совпадать с адресами в wwwroot/js/учебный-signalr.js:
// new signalR.HubConnectionBuilder().withUrl("/ТаблицаSignalRHub")
// new signalR.HubConnectionBuilder().withUrl("/УчебныйSignalRHub")
// ---------------------------------------------------------------------------
app.MapHub<ТаблицаSignalRHub>("/ТаблицаSignalRHub");
app.MapHub<УчебныйSignalRHub>("/УчебныйSignalRHub");

// Запускаем веб-сервер Kestrel/IIS Express/IIS, в зависимости от способа старта.
app.Run();
