namespace SignalRVisualizer.Models;

/// <summary>
/// Справочник каналов.
///
/// В реальном проекте каналов может быть несколько: для разных печей, линий,
/// общих таблиц, аудита машин и т.д. Каждый канал лучше хранить здесь.
/// </summary>
public static class МодельДляОпределенияКаналов
{
    /// <summary>
    /// Имя PostgreSQL-канала, который слушает BackgroundService.
    /// Такое же имя нужно использовать в SQL-команде NOTIFY.
    /// </summary>
    public const string Печь898Н2 = "та_34898_n2_channel";

    /// <summary>
    /// Белый список каналов, на которые клиенту разрешено подписываться.
    /// ТаблицаSignalRHub проверяет входящий канал по этому списку.
    /// </summary>
    public static readonly HashSet<string> Allowed = new()
    {
        Печь898Н2
    };

    /// <summary>
    /// Преобразует имя PostgreSQL-канала в имя SignalR-группы.
    ///
    /// Зачем нужна группа:
    /// - один браузер подписан на канал печи 898Н2;
    /// - другой браузер в будущем может быть подписан на другой канал;
    /// - сервер отправляет уведомление только нужной группе клиентов.
    /// </summary>
    public static string ПолучитьИмяГруппы(string канал)
    {
        return $"db_канал:{канал}";
    }
}
