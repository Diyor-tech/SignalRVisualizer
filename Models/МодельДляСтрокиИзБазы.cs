// ============================================================================
// МодельДляСтрокиИзБазы.cs
// ViewModel для страницы и partial-представления таблицы.
// ViewModel — модель, подготовленная специально для вывода в Razor.
// ============================================================================

namespace SignalRVisualizer.Models;

/// <summary>
/// Модель страницы с таблицей из PostgreSQL.
///
/// Важно: список сразу создается пустым, чтобы Razor-страница не падала,
/// даже если БД временно недоступна или запрос вернул 0 строк.
/// </summary>
public class МодельДляСтрокиИзБазы
{
    /// <summary>
    /// Список строк, который будет выведен в tbody таблицы.
    /// Каждая запись списка = одна строка HTML-таблицы.
    /// </summary>
    public List<Лист> ЛистДляТаблицыИзБазы { get; set; } = new();

    /// <summary>
    /// Текст ошибки загрузки данных.
    /// Если здесь есть текст, partial-представление покажет строку ошибки вместо данных.
    /// </summary>
    public string? ОшибкаЗагрузки { get; set; }

    /// <summary>
    /// Когда контроллер последний раз пытался перечитать таблицу.
    /// Показывается в блоке статуса над таблицей.
    /// </summary>
    public DateTime ВремяПоследнейЗагрузки { get; set; } = DateTime.Now;

    /// <summary>
    /// Одна строка таблицы _Диспозиция_поковок_ТА.
    /// Все поля сделаны string?, чтобы проще и безопаснее выводить их в Razor.
    /// Преобразование из типов PostgreSQL в строки выполняется в ГлавнаяController.
    /// </summary>
    public class Лист
    {
        public string? N_поз_ТА { get; set; }
        public string? N_ряда { get; set; }
        public string? Прав_поток_номер_поковки { get; set; }
        public string? Прав_поток_на_поддоне_количество { get; set; }
        public string? Прав_поток_на_поддоне_ед_измерения { get; set; }
        public string? Лев_поток_номер_поковки { get; set; }
        public string? Лев_поток_на_поддоне_количество { get; set; }
        public string? Лев_поток_на_поддоне_ед_измерения { get; set; }
        public string? Старт { get; set; }
    }
}
