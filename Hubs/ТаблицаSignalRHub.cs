// ============================================================================
// ТаблицаSignalRHub.cs
// SignalR Hub, который отвечает только за таблицу PostgreSQL.
// Он не читает БД сам. Он управляет подпиской клиента на группу канала и
// подтверждает ручной запрос обновления таблицы.
// ============================================================================

using Microsoft.AspNetCore.SignalR;
using SignalRVisualizer.Models;
using System.Diagnostics;

namespace SignalRVisualizer.Hubs;

/// <summary>
/// Hub для таблицы.
///
/// Поток работы:
/// 1. Браузер нажимает «Включить SignalR таблицы».
/// 2. JavaScript вызывает ПодключениеКСтранице(канал).
/// 3. Hub добавляет текущий ConnectionId в группу db_канал:...
/// 4. ПрослушкаКаналовБД отправляет уведомления именно в эту группу.
/// </summary>
public class ТаблицаSignalRHub : Hub
{
    /// <summary>
    /// Подписывает текущее SignalR-подключение браузера на группу канала.
    ///
    /// Важно: это не включает PostgreSQL LISTEN. PostgreSQL LISTEN уже работает
    /// в фоне в сервисе ПрослушкаКаналовБД. Этот метод только говорит:
    /// «данному браузеру можно отправлять события этого канала».
    /// </summary>
    public async Task ПодключениеКСтранице(string канал)
    {
        ПроверитьКанал(канал);

        string имяГруппы = МодельДляОпределенияКаналов.ПолучитьИмяГруппы(канал);
        await Groups.AddToGroupAsync(Context.ConnectionId, имяГруппы);

        Debug.WriteLine($"ID_Подключение: {Context.ConnectionId}, группа: {имяГруппы}");
    }

    /// <summary>
    /// Убирает текущее подключение из группы канала.
    /// После этого уведомления PostgreSQL могут продолжать приходить на сервер,
    /// но конкретный браузер их получать уже не будет.
    /// </summary>
    public async Task ОтключениеОтСтраницы(string канал)
    {
        ПроверитьКанал(канал);

        string имяГруппы = МодельДляОпределенияКаналов.ПолучитьИмяГруппы(канал);
        await Groups.RemoveFromGroupAsync(Context.ConnectionId, имяГруппы);

        Debug.WriteLine($"ID_Отключение: {Context.ConnectionId}, группа: {имяГруппы}");
    }

    /// <summary>
    /// Разовый запрос обновления таблицы через SignalR.
    ///
    /// Кнопка «Обновить таблицу через SignalR» должна работать даже тогда,
    /// когда автообновление по NOTIFY выключено. Поэтому JavaScript временно
    /// открывает соединение, вызывает этот метод, получает подтверждение и уже
    /// потом отдельным fetch() забирает HTML partial таблицы.
    ///
    /// Почему Hub не возвращает HTML сам:
    /// - Hub отвечает за real-time команды;
    /// - MVC Controller отвечает за чтение БД и Razor-разметку;
    /// - так обязанности разделены и код легче переносить в основной проект.
    /// </summary>
    public Task<МоделиЗапросаНаОбновлениеДанных> ЗапроситьРазовоеОбновлениеТаблицы(string канал)
    {
        ПроверитьКанал(канал);

        var ответ = new МоделиЗапросаНаОбновлениеДанных
        {
            Команда = "РазовоеОбновлениеТаблицы",
            Канал = канал,
            Таблицы = new List<string> { "_Диспозиция_поковок_ТА" }
        };

        return Task.FromResult(ответ);
    }

    /// <summary>
    /// SignalR автоматически вызывает этот метод, когда браузер закрыл вкладку,
    /// обновил страницу или потерял соединение.
    /// </summary>
    public override Task OnDisconnectedAsync(Exception? exception)
    {
        Debug.WriteLine($"ТаблицаSignalRHub: клиент отключился: {Context.ConnectionId}");
        return base.OnDisconnectedAsync(exception);
    }

    /// <summary>
    /// Защита от случайных/неразрешенных каналов.
    /// Без этой проверки клиент мог бы попросить подписать его на любой канал.
    /// Разрешенные каналы хранятся в МодельДляОпределенияКаналов.Allowed.
    /// </summary>
    private static void ПроверитьКанал(string канал)
    {
        if (string.IsNullOrWhiteSpace(канал) || !МодельДляОпределенияКаналов.Allowed.Contains(канал))
        {
            throw new HubException($"Канал '{канал}' не разрешен");
        }
    }
}
